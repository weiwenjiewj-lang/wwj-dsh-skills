#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""把 human_voice 规则组写入 rules.json（保持键序、无 BOM、缩进 1 空格）。

为什么用脚本改而不是手改：rules.json 有 3400+ 行，手工编辑极易破坏
JSON 结构或改变既有缩进/键序，而下游多个脚本都依赖它。
这里用 json round-trip 保证结构合法，并显式以 utf-8(no BOM) 写回
——库内所有 json 都是无 BOM 的，带 BOM 会让读取方静默降级。
"""
import io
import json
import os
import sys

sys.dont_write_bytecode = True

RULE_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                         'references', 'rules.json')

# ---------------------------------------------------------------- 规则正文
