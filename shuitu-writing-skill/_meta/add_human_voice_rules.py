                 "故上限取 50%／35%——只有**绝大多数段落用同一开头**才算单调。"
                 "单节通常只 4~8 段，样本少时占比会失真，"
                 "因此另设绝对次数：同一开头的段落 ≥4 段（6 段以上时 ≥3 段）即提示。"
